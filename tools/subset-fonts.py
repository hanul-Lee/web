"""Subset the original variable fonts to the site's text without changing design metrics."""
from pathlib import Path
from html.parser import HTMLParser
import hashlib
import json
import re
import sys

try:
    from fontTools import subset
    from fontTools.ttLib import TTFont
except ImportError:
    sys.exit('FontTools is required. Install tools/font-requirements.txt and set FONT_PYTHON to that Python interpreter.')

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'tools/font-sources'
DEST = ROOT / 'assets/fonts/subset'

class Text(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.hidden = 0
        self.parts = []
    def handle_starttag(self, tag, attrs):
        if tag in ('script', 'style'):
            self.hidden += 1
        self.parts.extend(value for key, value in attrs if value and key in ('alt', 'aria-label', 'title', 'content'))
    def handle_endtag(self, tag):
        if tag in ('script', 'style'):
            self.hidden = max(0, self.hidden - 1)
    def handle_data(self, data):
        if not self.hidden:
            self.parts.append(data)

def corpus():
    text = Text()
    for page in sorted(ROOT.glob('*.html')):
        text.feed(page.read_text())
    for name in ('case.js', 'components.js'):
        text.parts.append((ROOT / name).read_text())
    for name in ('shared.css', 'portfolio.css', 'case.css'):
        text.parts.extend(re.findall(r'''content:\s*["']([^"']*)["']''', (ROOT / name).read_text()))
    return {ord(char) for char in ''.join(text.parts)} | set(range(32, 127))

def expand_ranges(value):
    result = set()
    for token in value.split(','):
        token = token.strip().upper().removeprefix('U+')
        lo, _, hi = token.partition('-')
        result.update(range(int(lo, 16), int(hi or lo, 16) + 1))
    return result

def ranges(values):
    groups = []
    for point in sorted(values):
        if groups and point == groups[-1][1] + 1:
            groups[-1][1] = point
        else:
            groups.append([point, point])
    return ','.join('U+%X%s' % (lo, '-%X' % hi if hi != lo else '') for lo, hi in groups)

def main():
    wanted = corpus()
    css = (SOURCE / 'fonts.css').read_text()
    rules = []
    entries = []
    supported = set()
    covered = set()
    output = {}
    for block in re.findall(r'@font-face\s*\{([^}]+)\}', css):
        family = re.search(r"font-family:\s*'([^']+)'", block)[1]
        filename = re.search(r'src:\s*url\(([^)]+)\)', block)[1]
        allowed = expand_ranges(re.search(r'unicode-range:\s*([^;]+)', block)[1])
        font = TTFont(SOURCE / filename, recalcTimestamp=False)
        available = set(font.getBestCmap()) & allowed
        supported.update(available)
        selected = available & wanted
        if not selected:
            font.close()
            continue
        axes = [(axis.axisTag, axis.minValue, axis.defaultValue, axis.maxValue) for axis in font['fvar'].axes] if 'fvar' in font else []
        options = subset.Options()
        options.layout_features = ['*']
        options.name_IDs = ['*']
        options.recalc_timestamp = False
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=selected)
        subsetter.subset(font)
        assert set(font.getBestCmap()) >= selected, filename + ' lost required characters'
        if axes:
            assert [(axis.axisTag, axis.minValue, axis.defaultValue, axis.maxValue) for axis in font['fvar'].axes] == axes, 'variable axes changed'
        from io import BytesIO
        data = BytesIO()
        font.flavor = 'woff2'
        font.save(data)
        font.close()
        binary = data.getvalue()
        digest = hashlib.sha256(binary).hexdigest()[:12]
        target = filename.removesuffix('.woff2') + '-' + digest + '.woff2'
        output[target] = binary
        rules.append("@font-face {\n  font-family: '%s';\n  font-style: normal;\n  font-weight: 400 800;\n  font-display: swap;\n  src: url('subset/%s') format('woff2');\n  unicode-range: %s;\n}" % (family, target, ranges(selected)))
        entries.append({'family': family, 'source': filename, 'src': 'assets/fonts/subset/' + target, 'characters': len(selected), 'bytes': len(binary), 'axes': axes})
        covered.update(selected)
    assert wanted & supported <= covered, 'missing site glyphs'
    DEST.mkdir(parents=True, exist_ok=True)
    for filename, data in output.items():
        (DEST / filename).write_bytes(data)
    for old in DEST.glob('*.woff2'):
        if old.name not in output:
            old.unlink()
    stylesheet = '/* Generated by tools/subset-fonts.py. Original fonts and OFL licenses are retained. */\n' + '\n'.join(rules) + '\n'
    (ROOT / 'assets/fonts/fonts.css').write_text(stylesheet)
    manifest = {'sourceSupportedRanges': ranges(supported), 'coveredRanges': ranges(covered), 'fonts': entries}
    (ROOT / 'tools/font-manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
    version = hashlib.sha256(stylesheet.encode()).hexdigest()[:12]
    for page in ROOT.glob('*.html'):
        html = page.read_text()
        updated = re.sub(r'assets/fonts/fonts\.css\?v=[^"\s]+', 'assets/fonts/fonts.css?v=' + version, html)
        if updated != html:
            page.write_text(updated)
    print('Fonts: %d faces, %d bytes CSS, %d bytes WOFF2 (all pages); variable weights and layout features retained.' % (len(entries), len(stylesheet.encode()), sum(len(data) for data in output.values())))

if __name__ == '__main__':
    main()
